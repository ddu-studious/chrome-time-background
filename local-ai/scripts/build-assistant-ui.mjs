import { transform } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';

// Preserve classic-script/UMD globals and their existing order. esbuild's
// transform API optimizes the local sources without converting require branches
// into browser CommonJS wrappers or introducing a new runtime/module loader.
export const ASSISTANT_SCRIPTS = [
  'vendor/pinyin-match/pinyin-match.js', 'js/assistant-match.js',
  'js/music-intent.js', 'js/assistant-memory.js', 'js/assistant-contract.js',
  'js/assistant-todo.js', 'js/assistant-timeline.js', 'js/voice-live.js',
  'js/voice-input.js', 'js/assistant-voice.js', 'js/assistant.js'
];
const root = new URL('../../', import.meta.url);
export async function buildAssistantUI({ check = false } = {}) {
  const inputs = await Promise.all(ASSISTANT_SCRIPTS.map(async path => ({ path, text: await readFile(new URL(path, root), 'utf8') })));
  const hash = createHash('sha256').update(JSON.stringify(inputs)).digest('hex');
  const transformed = await transform(inputs.map(row => row.text).join('\n;\n'), {
    target: 'chrome142', charset: 'utf8', minifyWhitespace: true, minifySyntax: false,
    minifyIdentifiers: false, legalComments: 'inline', sourcefile: 'assistant-workbench.bundle.js'
  });
  const output = `/* Generated by local-ai/scripts/build-assistant-ui.mjs; do not edit.\n * Sources SHA256: ${hash}\n * PinyinMatch: MIT; see vendor/pinyin-match/LICENSE. Other sources: repository scripts.\n */\n${transformed.code}`;
  const target = new URL('js/assistant-workbench.bundle.js', root);
  if (check) {
    if (await readFile(target, 'utf8').catch(() => '') !== output) throw new Error('工作台构建产物已过期：请运行 node local-ai/scripts/build-assistant-ui.mjs');
  } else await writeFile(target, output);
  return { files: inputs.length, sourceBytes: inputs.reduce((sum, row) => sum + Buffer.byteLength(row.text), 0), outputBytes: Buffer.byteLength(output), hash };
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  console.log(JSON.stringify(await buildAssistantUI({ check: process.argv.includes('--check') })));
}
